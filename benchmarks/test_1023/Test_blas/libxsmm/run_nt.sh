for t in "${THREADS[@]}"; do
  export OMP_NUM_THREADS="$t"
  export OMP_DYNAMIC=FALSE   # 禁止动态线程数变化
  echo "==== OMP_NUM_THREADS=$OMP_NUM_THREADS ===="
  for c in "${CASES[@]}"; do
    # c: "M N K REP"
    read -r M N K REP <<< "$c"

    # 运行并捕获输出
    LINE=$($BIN "$M" "$N" "$K" "$REP" "$VERIFY" | grep "GFLOPS")

    # 示例输出格式：
    # LIBXSMM dgemm NT  m=384 n=83584 k=384 rep=100  time=0.712345 s  GFLOPS=2137.21
    # 用 awk 提取字段
    time_s=$(echo "$LINE" | awk '{for(i=1;i<=NF;i++) if($i ~ /^time=/){sub("time=","",$i); print $i}}')
    gflops=$(echo "$LINE" | awk '{for(i=1;i<=NF;i++) if($i ~ /^GFLOPS=/){sub("GFLOPS=","",$i); print $i}}')

    # 写入 CSV
    echo "$t,$M,$N,$K,$REP,$time_s,$gflops" >> "$OUT"

    # 同时打印到屏幕
